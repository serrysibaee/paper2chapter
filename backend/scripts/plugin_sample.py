"""Write the Obsidian plugin's bundled sample chapter from the backend's test fixture.

The plugin's settings preview renders this sample through the reader's settings (no model call, no write), and the
plugin's tests use it. Run from backend/ after the fixture or the parts format changes:

    .venv/Scripts/python scripts/plugin_sample.py      (Windows)
    .venv/bin/python scripts/plugin_sample.py          (macOS, Linux)
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.export_md import render_chapter_markdown, render_chapter_parts  # noqa: E402
from app.models import Chapter, PaperAnalysis  # noqa: E402

FIX = Path(__file__).resolve().parent.parent / "tests" / "fixtures"
OUT = Path(__file__).resolve().parent.parent.parent / "obsidian-plugin" / "src" / "sample.ts"


def render() -> str:
    """The text of the plugin's sample.ts, from the fixture."""
    chapter = Chapter.model_validate(json.loads((FIX / "chapter.json").read_text(encoding="utf-8")))
    analysis = PaperAnalysis.model_validate(json.loads((FIX / "analysis.json").read_text(encoding="utf-8")))
    md = render_chapter_markdown(chapter, flavor="obsidian")
    parts = render_chapter_parts(chapter, analysis=analysis, flavor="obsidian")
    sample = {"markdown": md.markdown, "assets": md.assets, "parts": parts.model_dump()}
    body = json.dumps(sample, ensure_ascii=False, indent="\t")
    return ("/* Generated by backend/scripts/plugin_sample.py from the backend's test fixture: do not edit by hand. */\n"
            "import type { ChapterParts } from './types.ts';\n\n"
            "export interface SampleChapter {\n\tmarkdown: string;\n\tassets: string[];\n\tparts: ChapterParts;\n}\n\n"
            f"export const SAMPLE: SampleChapter = {body};\n")


def main() -> None:
    OUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
