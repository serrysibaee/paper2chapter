"use client";

import Link from "next/link";
import { useParams } from "next/navigation";
import { useEffect, useMemo, useState } from "react";
import { ExerciseCard } from "@/components/ExerciseCard";
import { Markdown, TeX } from "@/components/Markdown";
import { VerifyBadge } from "@/components/VerifyBadge";
import { api, exportUrl } from "@/lib/api";
import type { MarkdownContext } from "@/lib/markdown";
import type { Chapter } from "@/lib/types";

export default function ChapterPage() {
  const { id } = useParams<{ id: string }>();
  const [ch, setCh] = useState<Chapter | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    api.chapter(id).then(setCh).catch((e) => setError(e.message));
  }, [id]);

  const ctx: MarkdownContext | null = useMemo(
    () => (ch ? { paperId: id, references: ch.references, figures: ch.figures, tables: ch.tables } : null),
    [ch, id],
  );
  const counts = useMemo(() => {
    const c = { verified: 0, failed: 0, error: 0, skipped: 0 };
    if (ch) for (const v of Object.values(ch.verification)) c[v.status]++;
    return c;
  }, [ch]);

  if (error) return <div className="alert error">{error} <Link href={`/papers/${id}`}>Back to paper</Link></div>;
  if (!ch || !ctx) return <p className="muted"><span className="spinner" /> Loading chapter…</p>;
  const v = ch.verification;

  return (
    <div className="reader">
      <nav className="toc" aria-label="Contents">
        <Link href={`/papers/${id}`} className="small">← Paper</Link>
        <ol>
          <li><a href="#intuition">Intuition first</a></li>
          {ch.primers.length > 0 && <li><a href="#prerequisites">Prerequisites</a></li>}
          {ch.sections.map((s) => <li key={s.id}><a href={`#${s.id}`}>{s.title}</a></li>)}
          <li><a href="#summary">Summary</a></li>
          <li><a href="#practice">Practice problems</a></li>
          <li><a href="#references">References</a></li>
        </ol>
        <div className="row" style={{ flexDirection: "column", alignItems: "stretch" }}>
          <a className="btn small" href={exportUrl(id)}>Download HTML</a>
          <a className="btn small ghost" href={exportUrl(id, false)}>HTML without solutions</a>
          <button className="btn small ghost" onClick={() => window.print()}>Print / save as PDF</button>
        </div>
      </nav>

      <article className="chapter">
        <h1>{ch.title}</h1>
        <p className="muted small" style={{ fontFamily: "var(--sans)" }}>
          Based on <em>{ch.paper_title}</em>{ch.paper_authors.length ? ` by ${ch.paper_authors.join(", ")}` : ""}.
          Generated by {ch.provider}/{ch.model} for {ch.options.audience} readers. Automated checks: {counts.verified} verified,{" "}
          {counts.failed} failed, {counts.error} not checkable. Machine-generated: verify important details against the paper.
        </p>
        {ch.warnings.length > 0 && (
          <div className="alert warn small" style={{ fontFamily: "var(--sans)" }}>
            {ch.warnings.map((w) => <div key={w}>{w}</div>)}
          </div>
        )}

        <div className="box">
          <div className="box-label">Learning objectives</div>
          <ul>{ch.learning_objectives.map((o) => <li key={o}><Markdown text={o} ctx={ctx} inline /></li>)}</ul>
        </div>

        <h2 id="intuition">Intuition first</h2>
        <Markdown text={ch.intuition_md} ctx={ctx} />

        {ch.primers.length > 0 && (
          <>
            <h2 id="prerequisites">Prerequisites</h2>
            <p className="muted">Short primers on background the rest of the chapter relies on.</p>
            {ch.primers.map((p) => (
              <section key={p.prerequisite_id}>
                <h3>{p.title}</h3>
                <Markdown text={p.intuition_md} ctx={ctx} />
                <Markdown text={p.explanation_md} ctx={ctx} />
                {p.key_formulas_latex.map((f) => <TeX key={f} latex={f} />)}
                <div className="example"><Markdown text={p.example_md} ctx={ctx} /></div>
                <ExerciseCard ex={p.check_question} ctx={ctx} verification={v[`ex:${p.check_question.id}`]} />
              </section>
            ))}
          </>
        )}

        {ch.notation.length > 0 && (
          <details>
            <summary style={{ fontFamily: "var(--sans)" }}>Notation ({ch.notation.length} symbols)</summary>
            <table>
              <tbody>
                {ch.notation.map((n) => (
                  <tr key={n.symbol_latex}><td><TeX latex={n.symbol_latex} display={false} /></td><td><Markdown text={n.meaning} inline /></td></tr>
                ))}
              </tbody>
            </table>
          </details>
        )}

        {ch.sections.map((s, i) => (
          <section key={s.id}>
            <h2 id={s.id}>{i + 1}. {s.title}</h2>
            <div className="box"><div className="box-label">Intuition</div><Markdown text={s.intuition_md} ctx={ctx} /></div>
            <Markdown text={s.body_md} ctx={ctx} />

            {s.derivations.map((d, di) => (
              <div className="derivation" key={di}>
                <h3>Derivation: {d.title}</h3>
                <Markdown text={d.goal_md} ctx={ctx} />
                {d.steps.map((step, k) => (
                  <div className="step" key={k}>
                    <div className="step-n">{k + 1}.</div>
                    <div>
                      <TeX latex={step.latex} />
                      <Markdown text={step.explanation_md} ctx={ctx} />
                      <div className="step-meta">
                        {step.justification} <VerifyBadge result={v[`deriv:${s.id}:${di}:${k}`]} />
                      </div>
                    </div>
                  </div>
                ))}
                <div className="box-label">Result</div>
                <TeX latex={d.result_latex} />
              </div>
            ))}

            {s.worked_examples.map((ex, e) => (
              <div className="example" key={e}>
                <h3>Worked example: {ex.title} <VerifyBadge result={v[`example:${s.id}:${e}`]} /></h3>
                <Markdown text={ex.problem_md} ctx={ctx} />
                <ol>{ex.solution_steps_md.map((st, k) => <li key={k}><Markdown text={st} ctx={ctx} /></li>)}</ol>
                <strong style={{ fontFamily: "var(--sans)" }}>Answer: </strong><Markdown text={ex.answer_md} ctx={ctx} />
              </div>
            ))}

            {s.check_questions.length > 0 && (
              <>
                <h3>Check your understanding</h3>
                {s.check_questions.map((q) => <ExerciseCard key={q.id} ex={q} ctx={ctx} verification={v[`ex:${q.id}`]} />)}
              </>
            )}
          </section>
        ))}

        <h2 id="summary">Summary</h2>
        <Markdown text={ch.summary_md} ctx={ctx} />
        <h3>Key takeaways</h3>
        <ul>{ch.key_takeaways.map((t) => <li key={t}><Markdown text={t} ctx={ctx} inline /></li>)}</ul>
        {ch.common_misconceptions.length > 0 && (
          <>
            <h3>Common misconceptions</h3>
            <ul>{ch.common_misconceptions.map((t) => <li key={t}><Markdown text={t} ctx={ctx} inline /></li>)}</ul>
          </>
        )}

        <h2 id="practice">Practice problems</h2>
        {ch.practice.map((q) => <ExerciseCard key={q.id} ex={q} ctx={ctx} verification={v[`ex:${q.id}`]} />)}

        {ch.further_reading.length > 0 && (
          <>
            <h2>Further reading</h2>
            <ul>
              {ch.further_reading.map((fr) => (
                <li key={fr.title}>
                  <strong>{fr.title}</strong>, {fr.authors}{fr.year ? `, ${fr.year}` : ""}. {fr.why}{" "}
                  {fr.ref_id ? <a className="cite" href={`#ref-${fr.ref_id}`}>[paper reference]</a> : <em className="muted small">(model suggestion, not from the paper: verify it exists)</em>}
                </li>
              ))}
            </ul>
          </>
        )}

        <h2 id="references">References (from the paper)</h2>
        {ch.references.length === 0 ? <p className="muted">No reference list was detected in the PDF.</p> : (
          <ol className="refs">
            {ch.references.map((r, i) => <li key={r.id} id={`ref-${r.id}`} value={r.number ?? i + 1}>{r.text}</li>)}
          </ol>
        )}
        <p className="muted small" style={{ fontFamily: "var(--sans)" }}>
          {ch.usage.calls} LLM requests · {(ch.usage.input_tokens + ch.usage.cache_read_tokens).toLocaleString()} input /{" "}
          {ch.usage.output_tokens.toLocaleString()} output tokens
          {ch.usage.cost_usd !== null ? ` · estimated cost $${ch.usage.cost_usd.toFixed(3)}` : ""} · generated {new Date(ch.generated_at).toLocaleString()}
        </p>
      </article>
    </div>
  );
}
